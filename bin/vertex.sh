#!/usr/bin/env bash

# The SERVER and CLOUD variables MUST BE set.
CLOUD=vertex
SERVER=ks-${CLOUD}-test

# Vertex/Gemini runs no local model engine, so a standard machine is plenty
# (there is no Ollama pod competing for node memory).
MACHINE_TYPE="e2-standard-4"

# ChatGXY/GalaxyAI is only in the Galaxy dev image; the `ai` mixin supplies that
# image plus the GalaxyAI branding. Its inference_services CPU tuning
# (structured_output_override:false, custom_tool off) is unnecessary on Gemini --
# which handles structured/tool-call output natively -- but it is harmless. Drop
# it later if you want Gemini to use full tool-calling.
MIXINS=(ai)

# Route GalaxyAI to Google Vertex AI (Gemini) via the LiteLLM front door. LiteLLM
# authenticates with the VM service account (Application Default Credentials over
# the GCE metadata server) -- no API key. Galaxy's config is unchanged; it still
# talks to LiteLLM. AI_MASTER_KEY (Galaxy<->LiteLLM) is auto-generated by
# launch_vm.sh. The Vertex model/location/project come from role defaults
# (gemini-2.5-flash, us-central1, project inferred from the VM credentials).
AI_BACKEND=vertex

# Modest storage: no Ollama model cache to hold, just Galaxy's own NFS PVC. A
# small reserve keeps Galaxy from claiming the entire disk (RabbitMQ + overhead
# share it).
DISK_SIZE=256
NFS_RESERVE=16

# The chatgxy branch (which carries the ai_backend=vertex support) lives on the
# personal fork used for test deploys; push it before launching (ansible-pull
# fetches REPO@BRANCH on the VM).
REPO=https://github.com/ksuderman/galaxy-k8s-boot
BRANCH=chatgxy

# Source the base script so the hi function is defined for the DESCRIPTION
DIR=$(dirname $(realpath $0))
source $DIR/start_base.sh

DESCRIPTION=$(cat <<EOF
    Quick-start wrapper around $(hi launch_vm.sh) with preset defaults for
    launching a Galaxy Kubernetes VM with GalaxyAI enabled, backed by Google
    Vertex AI (Gemini) through a LiteLLM front door. LiteLLM authenticates with
    the VM service account (ADC) -- no API key is required.
EOF
)
main "$@"

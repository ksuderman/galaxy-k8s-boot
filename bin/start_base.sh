#!/usr/bin/env bash

NAME=$(basename "$0")
DIR=$(dirname $(realpath $0))

ZONE=${ZONE:-us-east4-c}

# ANSI formatting
reset="\033[0m"
bold="\033[1m"

function hi() {
    echo -e "$bold$@$reset"
}

# The calling script MUST define the $SERVER variable.
if [[ -z $SERVER ]] ; then
    echo "    $(hi ERROR): The \$SERVER variable has not been defined in $NAME"
    exit 1
fi

# Values that may optionally be overridden in the calling script.
BRANCH=${BRANCH:-dev}
REPO=${REPO:-https://github.com/galaxyproject/galaxy-k8s-boot}
DISK_SIZE=${DISK_SIZE:-256}
DEPS_CHART=${DEPS_CHART:-""}
DEPS_VERSION=${DEPS_VERSION:-""}
CHART=${CHART:-""}
VERSION=${VERSION:-""}
# ChatGXY inference backend (none|ollama-cpu|ollama-gpu|external). When set to
# anything other than "none" the LiteLLM front door (and Ollama for ollama-*)
# is deployed and ChatGXY is enabled. AI_MASTER_KEY is auto-generated by
# launch_vm.sh when left empty.
AI_BACKEND=${AI_BACKEND:-""}
AI_MASTER_KEY=${AI_MASTER_KEY:-""}
# GPU selection for AI_BACKEND=ollama-gpu (see launch_vm.sh). GPU_TYPE is a GPU
# model (t4|l4|a100|h100); GPU_CPUS is the desired vCPU count (rounded up to a valid
# machine size); GPU_COUNT is the accelerator count (T4 only); GPU_MODEL overrides
# the Ollama model. Empty -> launch_vm.sh defaults.
GPU_TYPE=${GPU_TYPE:-""}
GPU_CPUS=${GPU_CPUS:-""}
GPU_COUNT=${GPU_COUNT:-""}
GPU_MODEL=${GPU_MODEL:-""}
# HTTPS at a hostname: GALAXY_HOSTNAME serves Galaxy over TLS (Let's Encrypt),
# ADDRESS attaches a reserved static IP so the public IP matches the DNS record,
# ACME_EMAIL is the Let's Encrypt account email. Empty -> launch_vm.sh defaults.
GALAXY_HOSTNAME=${GALAXY_HOSTNAME:-""}
ADDRESS=${ADDRESS:-""}
ACME_EMAIL=${ACME_EMAIL:-""}
# Publish LiteLLM's OpenAI-compatible API at https://<hostname>/llm/v1 (for Orbit).
# Requires GALAXY_HOSTNAME. Set to "true" to enable.
EXPOSE_LITELLM=${EXPOSE_LITELLM:-false}
# GiB reserved on the data disk so Galaxy does not claim the whole disk (leaves
# room for the Ollama model cache and RabbitMQ). Empty -> launch_vm.sh default.
NFS_RESERVE=${NFS_RESERVE:-""}
MACHINE_TYPE=${MACHINE_TYPE:-""}
# Override the base machine image (e.g. a GPU image with drivers baked in).
MACHINE_IMAGE=${MACHINE_IMAGE:-""}

DRY_RUN=""

function help() {
    cat << EOF

$(hi NAME)
    $NAME

$(hi DESCRIPTION)
$DESCRIPTION

$(hi SYNOPSIS)
    $NAME [start|stop|restart|kube|help]

$(hi OPTIONS)
    $(hi start)             start the Galaxy VM and allocate the disks
    $(hi stop)              stop the Galaxy VM and delete the disks
    $(hi restart)           stop then start the Galaxy VM
    $(hi pause)             stop the Galaxy VM but keep the disks
    $(hi resume)            start the Galaxy VM and reuse existing disks
    $(hi kube)              download the kubeconfig file for the cluster
    $(hi -h)|$(hi --help)|$(hi help)    show this help message

$(hi EXAMPLES)
    \$> $NAME
    \$> $NAME start
    \$> $NAME stop
    \$> $NAME help

EOF
}

if [[ $# -eq 0 ]] ; then
	help
	exit
fi

function start() {
	LAUNCH_CMD=($DIR/launch_vm.sh $SERVER
	  --git-repo $REPO
	  --git-branch $BRANCH
	  --disk-size $DISK_SIZE
	  --profile ''
	)
	if [[ $# -gt 0 ]] ; then
	    echo "Resuming ${SERVER}"
        LAUNCH_CMD+=("$@")
    else
    	echo "Launching ${SERVER}"
	fi
    if [[ -n $MACHINE_TYPE ]] ; then
        LAUNCH_CMD+=(--machine-type $MACHINE_TYPE)
    fi
    if [[ -n $ZONE ]] ; then
        LAUNCH_CMD+=(--zone $ZONE)
    fi
    if [[ -n $MACHINE_IMAGE ]] ; then
        LAUNCH_CMD+=(--machine-image $MACHINE_IMAGE)
    fi
	if [[ -n $DEPS_CHART ]] ; then
	    LAUNCH_CMD+=(--galaxy-deps-chart $DEPS_CHART)
	fi
	if [[ -n $DEPS_VERSION ]] ; then
	    LAUNCH_CMD+=(--galaxy-deps-version $DEPS_VERSION)
	fi
	if [[ -n $CHART ]] ; then
	    LAUNCH_CMD+=(--galaxy-chart $CHART)
	fi
	if [[ -n $VERSION ]] ; then
	    LAUNCH_CMD+=(--galaxy-chart-version $VERSION)
	fi
	if [[ -n $AI_BACKEND ]] ; then
	    LAUNCH_CMD+=(--ai-backend $AI_BACKEND)
	fi
	if [[ -n $AI_MASTER_KEY ]] ; then
	    LAUNCH_CMD+=(--ai-master-key $AI_MASTER_KEY)
	fi
	if [[ -n $GPU_TYPE ]] ; then
	    LAUNCH_CMD+=(--gpu-type $GPU_TYPE)
	fi
	if [[ -n $GPU_CPUS ]] ; then
	    LAUNCH_CMD+=(--gpu-cpus $GPU_CPUS)
	fi
	if [[ -n $GPU_COUNT ]] ; then
	    LAUNCH_CMD+=(--gpu-count $GPU_COUNT)
	fi
	if [[ -n $GPU_MODEL ]] ; then
	    LAUNCH_CMD+=(--gpu-model $GPU_MODEL)
	fi
	if [[ -n $GALAXY_HOSTNAME ]] ; then
	    LAUNCH_CMD+=(--hostname $GALAXY_HOSTNAME)
	fi
	if [[ -n $ADDRESS ]] ; then
	    LAUNCH_CMD+=(--address $ADDRESS)
	fi
	if [[ -n $ACME_EMAIL ]] ; then
	    LAUNCH_CMD+=(--acme-email $ACME_EMAIL)
	fi
	if [[ $EXPOSE_LITELLM == true ]] ; then
	    LAUNCH_CMD+=(--expose-litellm)
	fi
	if [[ -n $NFS_RESERVE ]] ; then
	    LAUNCH_CMD+=(--nfs-reserve $NFS_RESERVE)
	fi
    LAUNCH_CMD+=(-f values/values.yml)
	if [[ -n $MIXINS ]] ; then
	    for mixin in "${MIXINS[@]}" ; do
	        if [[ ! -f mixins/${mixin}.yml ]] ; then
	            echo "ERROR: Mixin ${mixin} does not exist."
	            exit 1
	        fi
	        LAUNCH_CMD+=(-f mixins/$mixin.yml)
	    done
	fi
	"${LAUNCH_CMD[@]}"
#	  -f mixins/local.yml \
#	  -f mixins/v26.1.yml

}

function stop() {
    echo "Deleting VM and disks for $SERVER"
	gcloud compute instances delete $SERVER --zone $ZONE --quiet
	for disk in $(gcloud compute disks list --filter="name~.*${SERVER}.*" --format='value(name)') ; do
		gcloud compute disks delete $disk --zone $ZONE --quiet
	done
}

function main() {
    case $1 in
        kube)
            if [[ -z $CLOUD ]] ; then
                echo "The name for the saved kubeconfig has not been set. Please check"
                echo "your startup script ($0)"
                exit 1
            fi
            if [[ -e .kubeconfig ]] ; then
                rm .kubeconfig
            fi
            $DIR/kube.sh --server $SERVER --cloud $CLOUD
            ;;
        pause)
            echo "Deleting VM for $SERVER"
	        gcloud compute instances delete $SERVER --zone $ZONE --quiet
            ;;
        start) start ;;
        stop) stop ;;
        restart|bounce)
            stop
            start
            ;;
        resume)
            start --restore-galaxy
            ;;
        -h|--help|help)
            help
            exit
            ;;
        *)
            echo "Unrecognized parameter $1"
            help
            exit 1
            ;;
    esac
}

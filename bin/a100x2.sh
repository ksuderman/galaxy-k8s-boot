#!/usr/bin/env bash

REPO=https://github.com/ksuderman/galaxy-k8s-boot
BRANCH=chatgxy

# The SERVER and CLOUD variables MUST BE set.
CLOUD=a100x2
SERVER=ks-${CLOUD}-test

# Two A100 40GB: GPU_TYPE=a100 + GPU_CPUS=24 -> launch_vm.sh picks a2-highgpu-2g
# (2x A100 40GB, 24 vCPU, 170GB RAM), 80GB aggregate VRAM. This draws on the 40GB
# A100 quota (NVIDIA_A100_GPUS), NOT the 80GB quota, so it works where a single
# a2-ultragpu (80GB) card is unavailable. A100 40GB zones: us-central1-{a,b,c},
# us-east1, us-east4-c, europe-west4-a. Override ZONE on stockout.
ZONE=${ZONE:-us-central1-f}
GPU_TYPE=a100
GPU_CPUS=24

# --------------------------------------------------------------------------------
# Serving engine selector: --engine ollama|vllm  (or ENGINE=ollama|vllm), default
# ollama. Both run a 4-bit ~72B across the two GPUs; ollama layer-splits, vllm does
# true tensor parallelism (better throughput, newer path here). The playbook sets the
# GPU count (ollama_gpu_count / vllm_tensor_parallel_size) from the node automatically.
# --------------------------------------------------------------------------------
ENGINE="${ENGINE:-ollama}"
ARGS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        --engine) ENGINE="$2"; shift 2 ;;
        --engine=*) ENGINE="${1#*=}"; shift ;;
        *) ARGS+=("$1"); shift ;;
    esac
done
set -- "${ARGS[@]}"

case "$ENGINE" in
    ollama)
        # Ollama's qwen2.5:72b is Q4_K_M (~47GB); GPU_MODEL overrides ollama_model_gpu.
        AI_BACKEND=ollama-gpu
        GPU_MODEL=qwen2.5:72b
        # The 20Gi role default can't hold a ~47GB model; size the cache PVC generously.
        GPU_STORAGE=60Gi
        ;;
    vllm)
        # vLLM serves the AWQ 4-bit Qwen2.5-72B from the role default (vllm_model);
        # override there or with -e to change it. Storage comes from vllm_storage_size.
        AI_BACKEND=vllm-gpu
        ;;
    *)
        echo "ERROR: --engine must be 'ollama' or 'vllm' (got '$ENGINE')."
        exit 1
        ;;
esac

# GPU machine image with the NVIDIA driver + container toolkit baked in (same Ampere
# driver branch drives the A100); gpu_setup.yml then only verifies the driver.
MACHINE_IMAGE="galaxy-k8s-boot-gpu-debian12-v2026-07-09"

# Self-hosted GPU inference behind LiteLLM. AI_MASTER_KEY is auto-generated by
# launch_vm.sh when left empty.
AI_MASTER_KEY=$(cat /dev/urandom | LC_ALL=C tr -dc a-z0-9 | head -c 32)

# TLS + Orbit access: serve Galaxy over HTTPS at a hostname and expose LiteLLM's
# OpenAI-compatible API at https://<hostname>/llm/v1.
GALAXY_HOSTNAME=a100x2.galaxy.useanvil.org
case $ZONE in
    us-central*) ADDRESS=ks-a100-ip-central1 ;;
    us-east1*)   ADDRESS=ks-a100-ip-east1 ;;
    *)
        echo "There are no reserved IP addresses for zone $ZONE"
        exit 1
        ;;
esac
ACME_EMAIL=suderman@jhu.edu
EXPOSE_LITELLM=true

MIXINS=(a100x2 multiuser admins postinstall-ks)

# The model cache uses the blockstorage (local-path) class on the data disk; reserve
# enough headroom that Galaxy's NFS claim does not starve it (vllm_storage_size is
# 120Gi, ollama's cache 60Gi -- 160GiB covers either with room for RabbitMQ).
DISK_SIZE=1024
NFS_RESERVE=160

# Source the base script so the hi function is defined for the DESCRIPTION
DIR=$(dirname $(realpath $0))
source $DIR/start_base.sh

DESCRIPTION=$(cat <<EOF
    Quick-start wrapper around $(hi launch_vm.sh) with preset defaults for launching a
    Galaxy Kubernetes VM with GalaxyAI enabled, backed by a self-hosted 70B model on
    two NVIDIA A100 40GB GPUs (a2-highgpu-2g) behind a LiteLLM front door. Select the
    serving engine with $(hi "--engine ollama|vllm") (default ollama).
EOF
)
main "$@"
